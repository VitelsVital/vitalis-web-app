import gsap from "gsap";

import TransitionLayer from "../TransitionLayer";

class MenuTransition {
  /*
  |--------------------------------------------------------------------------
  | Shared Transition Layer
  |--------------------------------------------------------------------------
  */

  private readonly layer: TransitionLayer;

  /*
  |--------------------------------------------------------------------------
  | MENU VISIBILITY TIMING
  |--------------------------------------------------------------------------
  */

  private readonly OPEN_MENU_TIME = 0.2;

  private readonly CLOSE_MENU_TIME = 0.3;

  /*
  |--------------------------------------------------------------------------
  | Constructor
  |--------------------------------------------------------------------------
  */

  constructor(layer: TransitionLayer) {
    this.layer = layer;
  }

  /*
  |--------------------------------------------------------------------------
  | OPEN
  |--------------------------------------------------------------------------
  */

  open(onMenuVisible?: () => void): Promise<void> {
    /*
    |--------------------------------------------------------------------------
    | Reset
    |--------------------------------------------------------------------------
    */

    this.layer.reset();

    /*
    |--------------------------------------------------------------------------
    | Screens
    |--------------------------------------------------------------------------
    */

    const screenOne = this.layer.getScreenOne();

    const screenTwo = this.layer.getScreenTwo();

    /*
    |--------------------------------------------------------------------------
    | Show
    |--------------------------------------------------------------------------
    */

    this.layer.show();

    /*
    |--------------------------------------------------------------------------
    | Layering
    |--------------------------------------------------------------------------
    */

    gsap.set(screenOne, {
      zIndex: 2,
    });

    gsap.set(screenTwo, {
      zIndex: 1,
    });

    /*
    |--------------------------------------------------------------------------
    | Timeline
    |--------------------------------------------------------------------------
    */

    return new Promise((resolve) => {
      const timeline = gsap.timeline({
        onComplete: () => {
          /*
          |--------------------------------------------------------------------------
          | Hide
          |--------------------------------------------------------------------------
          */

          this.layer.hide();

          /*
          |--------------------------------------------------------------------------
          | Reset
          |--------------------------------------------------------------------------
          */

          this.layer.reset();

          resolve();
        },
      });

      /*
      |--------------------------------------------------------------------------
      | Screen One
      |--------------------------------------------------------------------------
      */

      timeline.to(
        screenOne,
        {
          yPercent: -200,
          duration: 1.2,
          ease: "power3.out",
        },
        0,
      );

      /*
      |--------------------------------------------------------------------------
      | Screen Two
      |--------------------------------------------------------------------------
      */

      timeline.to(
        screenTwo,
        {
          yPercent: -200,
          duration: 1.08,
          ease: "power3.out",
        },
        0.15,
      );

      /*
      |--------------------------------------------------------------------------
      | Menu Visibility
      |--------------------------------------------------------------------------
      */

      timeline.call(
        () => {
          onMenuVisible?.();
        },
        [],
        this.OPEN_MENU_TIME,
      );
    });
  }

  /*
  |--------------------------------------------------------------------------
  | CLOSE
  |--------------------------------------------------------------------------
  */

  close(onMenuHidden?: () => void): Promise<void> {
    /*
    |--------------------------------------------------------------------------
    | Reset
    |--------------------------------------------------------------------------
    */

    this.layer.reset();

    /*
    |--------------------------------------------------------------------------
    | Screens
    |--------------------------------------------------------------------------
    */

    const screenOne = this.layer.getScreenOne();

    const screenTwo = this.layer.getScreenTwo();

    /*
    |--------------------------------------------------------------------------
    | Show
    |--------------------------------------------------------------------------
    */

    this.layer.show();

    /*
    |--------------------------------------------------------------------------
    | Layering
    |--------------------------------------------------------------------------
    */

    gsap.set(screenTwo, {
      zIndex: 2,
    });

    gsap.set(screenOne, {
      zIndex: 1,
    });

    /*
    |--------------------------------------------------------------------------
    | Timeline
    |--------------------------------------------------------------------------
    */

    return new Promise((resolve) => {
      const timeline = gsap.timeline({
        onComplete: () => {
          /*
          |--------------------------------------------------------------------------
          | Hide
          |--------------------------------------------------------------------------
          */

          this.layer.hide();

          /*
          |--------------------------------------------------------------------------
          | Reset
          |--------------------------------------------------------------------------
          */

          this.layer.reset();

          resolve();
        },
      });

      /*
      |--------------------------------------------------------------------------
      | Screen Two
      |--------------------------------------------------------------------------
      */

      timeline.to(
        screenTwo,
        {
          yPercent: -200,
          duration: 1.2,
          ease: "power3.out",
        },
        0,
      );

      /*
      |--------------------------------------------------------------------------
      | Screen One
      |--------------------------------------------------------------------------
      */

      timeline.to(
        screenOne,
        {
          yPercent: -200,
          duration: 1.08,
          ease: "power3.out",
        },
        0.15,
      );

      /*
      |--------------------------------------------------------------------------
      | Menu Visibility
      |--------------------------------------------------------------------------
      */

      timeline.call(
        () => {
          onMenuHidden?.();
        },
        [],
        this.CLOSE_MENU_TIME,
      );
    });
  }

  /*
  |--------------------------------------------------------------------------
  | Destroy
  |--------------------------------------------------------------------------
  |
  | Do NOT destroy the shared TransitionLayer here.
  |
  */

  destroy(): void {
    gsap.killTweensOf([this.layer.getScreenOne(), this.layer.getScreenTwo()]);
  }
}

export default MenuTransition;
